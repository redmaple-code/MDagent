#!/usr/bin/env python3
"""Generate a per-user local deployment; never install system sudo rules."""
import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import shlex
import stat
import tempfile

MARKER = "# Generated by MDagent Ubuntu installer"
UNITS = ("mdagent-web.service", "mdagent-dashboard.service", "mdagent-orchestrator.service", "mdagent-evolution.timer")


def checked_path(value):
    path = Path(value).expanduser().absolute()
    if any(c in str(path) for c in "\r\n\x00"):
        raise ValueError("Paths cannot contain line breaks or NUL")
    for part in (path, *path.parents):
        if part.is_symlink():
            raise ValueError("Deployment path contains a symbolic link")
    return path


def write_generated(path, content, mode=0o600):
    checked_path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        if not stat.S_ISREG(path.stat().st_mode):
            raise ValueError("Generated target is not a regular file")
        if MARKER not in path.read_text(encoding="utf-8"):
            raise ValueError("Refusing to replace a file not generated by this installer: " + path.name)
    fd, temporary = tempfile.mkstemp(prefix=".mdagent-", dir=path.parent)
    try:
        os.fchmod(fd, mode) if hasattr(os, "fchmod") else None
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as output:
            output.write(content)
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def create_once_json(path, content):
    checked_path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        if not stat.S_ISREG(path.stat().st_mode):
            raise ValueError("Runtime state target is not a regular file")
        return
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as output:
        json.dump(content, output, ensure_ascii=False, indent=2)


def systemd_quote(value):
    # systemd specifiers must be escaped even within quoted arguments.
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$") + '"'


def check_previous(code, data, kit, cases, engine, unit_dir, mpirun="/usr/bin/mpirun"):
    code, data, kit, cases, unit_dir = map(checked_path, (code, data, kit, cases, unit_dir))
    if engine not in ("lammps", "both", "none"):
        raise ValueError("Unknown engine")
    metadata = {"format": 1, "code_root": str(code), "data_root": str(data), "kit": str(kit),
                "run_case_base": str(cases), "engine": engine, "unit_dir": str(unit_dir),
                "runner": str(data / "bin/mdagent-local"), "services": list(UNITS),
                "mpirun": str(checked_path(mpirun))}
    existing = data / "install.json"
    if existing.exists():
        previous = json.loads(existing.read_text(encoding="utf-8"))
        if previous != metadata:
            raise ValueError("Existing installation choices differ; use a separate data root")
    return metadata


def generate(code, data, kit, cases, engine, unit_dir, mpirun="/usr/bin/mpirun"):
    code, data, kit, cases, unit_dir = map(checked_path, (code, data, kit, cases, unit_dir))
    metadata = check_previous(code, data, kit, cases, engine, unit_dir, mpirun)
    if not (code / "run-dsh.sh").is_file() or not (kit / "agents/runtime/v3.3/orchestrator.py").is_file():
        raise ValueError("Missing code root or prepared kit entry")
    existing = data / "install.json"
    cases.mkdir(parents=True, exist_ok=True)
    (kit / "logs").mkdir(exist_ok=True)
    create_once_json(kit / ".v3.3_state.json", {
        "version": "3.3", "phase": "IDLE", "monitor_subphase": "OBSERVE",
        "monitor_subphase_history": [], "task": None, "agents": {},
        "recovery_history": [], "history": [], "last_tick": None,
    })
    create_once_json(kit / "status_bus.json", {
        "version": "1.0.0", "timestamp": datetime.now(timezone.utc).isoformat(),
        "cases": {}, "agents": {},
        "system": {"loadavg": list(os.getloadavg()) if hasattr(os, "getloadavg") else [0, 0, 0],
                   "total_cores": os.cpu_count() or 1},
    })
    runtime = data / "runtime"
    mpi_vars = runtime / "openmpi-env.sh"
    write_generated(mpi_vars, MARKER + "\n# OpenMPI is already available through the managed PATH.\n", 0o600)
    values = {
        "MDAGENT_CODE_ROOT": str(code), "MDSIM_DATA_ROOT": str(data),
        "DSH_HOME": str(data / "dsh-home"), "MDSIM_KIT_BASE": str(kit),
        "AGENT_BASE": str(kit), "RUN_CASE_BASE": str(cases),
        "AGENTS_DIR": str(kit / "agents/runtime/v3.3"),
        "MDSIM_PYTHON": str(runtime / "venv/bin/python"),
        "MDSIM_NODE_BIN": str(runtime / "node/bin"),
        "MDSIM_REGISTER_SCRIPT": str(code / "scripts/register_job.py"),
        "LMP": str(data / "bin/lmp_mpi") if engine != "none" else "",
        "MPIRUN": metadata["mpirun"], "MPI_VARS": str(mpi_vars),
        "DSH_PERMISSION_MODE": "workspace-write", "WEB_HOST": "127.0.0.1",
        "MDAGENT_ENGINE": engine,
    }
    prefix = ":".join(str(p) for p in (data / "bin", runtime / "node/bin", runtime / "npm-tools/bin", runtime / "venv/bin"))
    env = MARKER + "\n" + "\n".join("export " + key + "=" + shlex.quote(value) for key, value in values.items())
    env += "\nexport PATH=" + shlex.quote(prefix) + ':"$PATH"\n'
    write_generated(data / "install.env", env)
    runner = "#!/usr/bin/env bash\n" + MARKER + "\nset -euo pipefail\n"
    runner += "source " + shlex.quote(str(data / "install.env")) + "\n"
    runner += '''cd "$MDAGENT_CODE_ROOT"
case "${1:-web}" in
  web) exec bash "$MDAGENT_CODE_ROOT/run-dsh.sh" web --host 127.0.0.1 --port 3091 ;;
  dashboard) exec "$MDSIM_PYTHON" "$MDAGENT_CODE_ROOT/dashboard/web_monitor.py" 8080 ;;
  orchestrator) exec "$MDSIM_PYTHON" "$AGENT_BASE/agents/runtime/v3.3/orchestrator.py" ;;
  observe) exec "$MDSIM_PYTHON" "$MDAGENT_CODE_ROOT/evolution/observe.py" ;;
  check) exec "$MDSIM_PYTHON" "$MDAGENT_CODE_ROOT/scripts/install_check.py" --data-root "$MDSIM_DATA_ROOT" ;;
  tui) exec bash "$MDAGENT_CODE_ROOT/run-dsh.sh" --profile tui ;;
  *) echo "Usage: mdagent-local {web|dashboard|orchestrator|observe|check|tui}" >&2; exit 2 ;;
esac
'''
    runner_path = data / "bin/mdagent-local"
    write_generated(runner_path, runner, 0o700)
    for name, command in (("web", "web"), ("dashboard", "dashboard"), ("orchestrator", "orchestrator"), ("evolution", "observe")):
        unit = MARKER + "\n[Unit]\nDescription=MDagent " + name + "\n\n[Service]\n"
        unit += "Type=" + ("oneshot" if name == "evolution" else "simple") + "\n"
        unit += "ExecStart=/bin/bash " + systemd_quote(runner_path) + " " + command + "\n"
        unit += "UMask=0077\n"
        if name != "evolution":
            unit += "Restart=on-failure\nRestartSec=5\n\n[Install]\nWantedBy=default.target\n"
        write_generated(unit_dir / ("mdagent-" + name + ".service"), unit)
    timer = MARKER + "\n[Unit]\nDescription=MDagent periodic observations\n\n[Timer]\nOnBootSec=5min\nOnUnitActiveSec=37min\nUnit=mdagent-evolution.service\n\n[Install]\nWantedBy=timers.target\n"
    write_generated(unit_dir / "mdagent-evolution.timer", timer)
    # Metadata contains paths and installation choices only; no model credentials.
    create_once_json(existing, metadata)
    if json.loads(existing.read_text(encoding="utf-8")) != metadata:
        raise ValueError("Existing installation choices differ; use a separate data root")
    return metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for flag in ("code-root", "data-root", "kit", "run-case-base"):
        parser.add_argument("--" + flag, required=True)
    parser.add_argument("--engine", choices=("lammps", "both", "none"), default="both")
    parser.add_argument("--unit-dir", default=str(Path.home() / ".config/systemd/user"))
    parser.add_argument("--check-only", action="store_true")
    parser.add_argument("--mpirun", default="/usr/bin/mpirun")
    args = parser.parse_args()
    try:
        operation = check_previous if args.check_only else generate
        operation(args.code_root, args.data_root, args.kit, args.run_case_base, args.engine, args.unit_dir, args.mpirun)
    except (OSError, ValueError) as error:
        parser.exit(1, "Local deployment preparation failed: " + str(error) + "\n")
    print("Local launcher and user service units prepared. No model request or job was submitted.")


if __name__ == "__main__":
    main()
